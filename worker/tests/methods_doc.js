#!/usr/bin/env node
// Writes docs/ask/METHODS_REVIEW.md: the plain-language review sheet of the standard-method library (docs/ask/methods.js) for the
// site owner — every method's title, rule, parameters and an example question, with a sign-off line.
//   node worker/tests/methods_doc.js          (rewrites the file; methods.test.js fails when it is stale)
// The sheet carries no date of its own, so it changes only when a method changes.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { METHODS, PARAMS, MEASURES, isReviewed } from '../../docs/ask/methods.js';

const HERE = path.dirname(fileURLToPath(import.meta.url)); const ROOT = path.resolve(HERE, '..', '..');
const PARAM_WORDS = { state: 'the state', place: 'one place (a county, district or state)', county: 'one county', district: 'one congressional district', query: 'a ZIP code or town as typed', measure: 'which access measure (see the list at the top)', n: 'how many places to list', cancer_type: 'a trial cancer type (e.g. breast, lung)', phase: 'a trial phase (1, 1-2, 2, 2-3, 3, 4, NA)', site: 'an incidence / death-rate site (default all sites)' };

export function reviewSheet() {
  const out = [];
  out.push('# Standard methods — review sheet', '');
  out.push('These are the fixed rules the question box uses for the site\'s core questions. When a visitor\'s question fits one, the box runs the rule exactly as written below instead of composing its own query, and the answer card says "Standard method: <title>". Once a rule has been read and signed off here, set `reviewed_by` and `reviewed_on` for that method in `docs/ask/methods.js`; the card then says "Reviewed method · <name>, <date>". Nobody else sets those two fields.', '');
  out.push('Generated by `node worker/tests/methods_doc.js` from `docs/ask/methods.js`; do not edit by hand (the tests fail when this file is out of date).', '');
  out.push(`${METHODS.length} methods; ${METHODS.filter(isReviewed).length} reviewed.`, '');
  out.push('## The access measures a ranking can use', '');
  for (const [k, m] of Object.entries(MEASURES)) out.push(`- **${k}**${k === 'short' ? ' (default)' : ''}: ${m.words}. Worst = ${m.worst === 'desc' ? 'highest' : 'lowest'}.`);
  out.push('');
  METHODS.forEach((m, i) => {
    out.push(`## ${i + 1}. ${m.title}`, '');
    out.push(`*id:* \`${m.id}\`${isReviewed(m) ? ` · **Reviewed by ${m.reviewed_by}, ${m.reviewed_on}**` : ' · not reviewed yet'}`, '');
    out.push(`**Rule.** ${m.rule}`, '');
    out.push(`**Asks for:** ${m.params.length ? m.params.map(k => `${PARAM_WORDS[k] || k}${m.required.includes(k) ? '' : ' (optional)'}`).join('; ') : 'nothing'}.`, '');
    out.push(`**Example question:** "${m.example}"`, '');
    out.push('- [ ] The rule is right as written.   Reviewed by: ____________   Date: ________', '- Notes / changes wanted:', '');
  });
  out.push('## Parameters, as the box passes them', '');
  for (const [k, p] of Object.entries(PARAMS)) out.push(`- \`${k}\`: ${p.desc}${p.enum ? ` One of: ${p.enum.join(', ')}.` : ''}`);
  out.push('');
  return out.join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const file = path.join(ROOT, 'docs/ask/METHODS_REVIEW.md');
  fs.writeFileSync(file, reviewSheet());
  console.log(`wrote ${path.relative(ROOT, file)} (${METHODS.length} methods)`);
}
